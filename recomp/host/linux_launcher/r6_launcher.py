#!/usr/bin/env python3
"""Rainbow Six's launch window on Linux (the co-op mod's launcher), laid out like the Dungeon Siege / Delta Force ports':
the game's own main-menu art as a banner, the Controls row (Classic / Modern / Custom), and a button per group of
settings that opens it as a panel of rows (click or arrow keys to change; text rows edit in place). KEY GUIDE lists
every action's keys and rebinds any of them (click, then press a key or a mouse button).

Everything is written where the game reads it in the native build: options in <data>/registry.txt (the runtime's
registry: key<TAB>name<TAB>type<TAB>hex), controls in <data>/game/sherman.kmp. The rows, actions, key names and the two
layouts come from r6coop-launcher.json, generated by the mod (launcher/gen_spec.py) and shared with the Windows and
macOS launchers. The banner is <game>/data/bitmap/mm_bg.RSB from the player's own copy.

Usage: r6_launcher.py --binary <RainbowSixLinux> --exe <RainbowSix.exe> --game <game folder> --data <data folder>
DS_NO_LAUNCHER=1 or DS_TEST starts the game directly; DS_LAUNCHER_SHOT=<png> renders the window to a file and exits."""
import argparse
import json
import os
import struct
import sys
from pathlib import Path

KEY = "hklm\\software\\red storm entertainment\\tom clancy's rainbow six"
REG_SZ, REG_DWORD = 1, 4


# ---------------------------------------------------------------- settings: registry.txt and sherman.kmp
class Registry:
    """the runtime's registry.txt: kept whole, values of the game's key read and replaced"""
    def __init__(self, path):
        self.path = path
        self.lines = path.read_text(errors='replace').splitlines() if path.exists() else []

    def get(self, name):
        for line in self.lines:
            p = line.split('\t')
            if len(p) == 4 and p[0].lower() == KEY and p[1].lower() == name.lower():
                return int(p[2]), bytes.fromhex(p[3])
        return None

    def set(self, name, typ, data):
        new = f'{KEY}\t{name}\t{typ}\t{data.hex()}'
        for i, line in enumerate(self.lines):
            p = line.split('\t')
            if len(p) == 4 and p[0].lower() == KEY and p[1].lower() == name.lower():
                self.lines[i] = new
                return
        self.lines.append(new)

    def save(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        tmp = self.path.with_suffix('.txt.tmp')
        tmp.write_text('\n'.join(self.lines) + '\n')
        tmp.replace(self.path)


def read_value(reg, row):
    v = reg.get(row['reg']) if row.get('reg') else None
    if not v:
        return row.get('default', '')
    typ, data = v
    if row.get('store') == 'dword' and typ == REG_DWORD and len(data) == 4:
        return str(struct.unpack('<I', data)[0])
    return data.split(b'\0', 1)[0].decode('latin-1')   # REG_SZ, or the game's number-as-text


def write_value(reg, row, value):
    if not row.get('reg') or row['type'] == 'controls':
        return
    store = row.get('store', 'sz')
    if store == 'dword':
        reg.set(row['reg'], REG_DWORD, struct.pack('<I', int(value or 0)))
    elif store == 'dwordtext':
        reg.set(row['reg'], REG_DWORD, value.encode('latin-1'))           # the game's own form: text, type 4
    else:
        reg.set(row['reg'], REG_SZ, value.encode('latin-1') + b'\0')


def read_kmp(path):
    """the whole 257-byte sherman.kmp: byte 0 the mouselook flag, then the action of each key code"""
    try:
        b = path.read_bytes()
        if len(b) == 257 and b[0] <= 1:
            return bytearray(b)
    except OSError:
        pass
    return None


def write_kmp(path, table):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(bytes(table))           # always all 257 bytes: a short file makes the game repeat its last byte


def read_rsb(path):
    """RSB: u32 version, width, height, 0, bit counts R G B A (5 6 5 0), then 16-bit pixels, top row first"""
    try:
        d = path.read_bytes()
        w, h = struct.unpack_from('<II', d, 4)
        if struct.unpack_from('<4I', d, 16) != (5, 6, 5, 0) or len(d) < 32 + w * h * 2:
            return None
        return w, h, d[32:32 + w * h * 2]
    except (OSError, struct.error):
        return None


# ---------------------------------------------------------------- the window
def main():
    ap = argparse.ArgumentParser()
    for name in ('binary', 'exe', 'game', 'data'):
        ap.add_argument('--' + name, required=True)
    ap.add_argument('--spec')
    args = ap.parse_args()
    data, game = Path(args.data), Path(args.game)
    command = [args.binary, '--exe', args.exe, '--game', args.game, '--data', args.data]
    shot = os.environ.get('DS_LAUNCHER_SHOT')
    if (os.environ.get('DS_TEST') or os.environ.get('DS_NO_LAUNCHER')) and not shot:
        os.execv(command[0], command)

    spec_path = Path(args.spec) if args.spec else next(
        (p for p in (game / 'r6coop-launcher.json', Path(args.exe).with_name('r6coop-launcher.json'),
                     Path(__file__).with_name('r6coop-launcher.json')) if p.exists()), None)
    if not spec_path:
        os.execv(command[0], command)              # no launcher description: just play
    spec = json.loads(spec_path.read_text())
    rows = {r['id']: r for r in spec['rows']}
    reg = Registry(data / 'registry.txt')
    values = {rid: read_value(reg, r) for rid, r in rows.items()}
    kmp_path = data / 'game' / spec.get('kmp_file', 'sherman.kmp')
    layouts = {name: bytearray(t) for name, t in spec['layouts'].items()}   # classic, modern, keyboard: 257 bytes each
    classic = layouts['classic']
    keys = read_kmp(kmp_path) or bytearray(classic)
    key_names = {int(c): k['name'] for c, k in spec['keys'].items()}
    vk_to_code = {k['vk']: int(c) for c, k in spec['keys'].items() if k.get('vk') is not None}
    mouse = spec.get('mouse', {})

    from PySide6.QtCore import Qt, QRect, QRectF
    from PySide6.QtGui import QColor, QFont, QImage, QPainter, QPen
    from PySide6.QtWidgets import QApplication, QLineEdit, QMessageBox, QWidget

    app = QApplication(sys.argv[:1])
    app.setApplicationName('rainbow-six')

    # a "modes" row (Mission Resolution) also offers the desktop's own size; the host shows any size letterboxed
    screen = app.primaryScreen()
    if screen:
        dpr = screen.devicePixelRatio()
        dw, dh = int(screen.size().width() * dpr), int(screen.size().height() * dpr)
        for r in rows.values():
            ch = r.get('choices', [])
            if r.get('modes') and dw >= 640 and dh >= 480 and not any(c['value'] == f'{dw}x{dh}' for c in ch):
                ch.append({'value': f'{dw}x{dh}', 'label': f'{dw} x {dh}', 'note': 'This display'})
                ch.sort(key=lambda c: tuple(int(v) for v in c['value'].split('x')) if 'x' in c['value'] else (0, 0))
    app.setApplicationDisplayName('Rainbow Six co-op')
    app.setDesktopFileName('rainbow-six')
    W, H, BANNER = 760, 700, 200
    ROW_X, ROW_W, ROW_H = 70, 760 - 140, 46
    TEAL, TEAL_DIM, TEXT, NOTE, ACCENT = QColor(46, 196, 196), QColor(24, 110, 112), QColor(214, 236, 236), QColor(120, 160, 160), QColor(255, 214, 58)
    BG, PANEL, PANEL_HOT = QColor(6, 12, 14), QColor(10, 26, 30), QColor(16, 42, 46)
    art = read_rsb(game / 'data' / 'bitmap' / 'mm_bg.RSB')
    art_img = QImage(art[2], art[0], art[1], art[0] * 2, QImage.Format_RGB16).copy() if art else None

    def layout_name(t):
        return next((n for n, l in layouts.items() if t == l), 'custom')

    def number(s):
        try:
            return float(s)
        except (TypeError, ValueError):
            return None

    class Launcher(QWidget):
        def __init__(self):
            super().__init__()
            self.setFixedSize(W, H)
            self.setWindowTitle('Rainbow Six co-op')
            self.setMouseTracking(True)
            self.open, self.focus, self.hover, self.bind, self.scroll = -1, 0, None, None, 0
            self.edit = None
            self.f_title = QFont('Arial Black', 30, QFont.Black)
            self.f_big = QFont('Arial', 13, QFont.Bold)
            self.f_row = QFont('Arial', 11, QFont.DemiBold)
            self.f_small = QFont('Arial', 9)

        # ---- model
        def items(self):
            return spec['top'] if self.open < 0 else spec['groups'][self.open]['rows']

        def guide(self):
            return self.open >= 0 and spec['groups'][self.open].get('guide')

        def choice_index(self, rid):
            r = rows[rid]
            if r['type'] == 'controls':
                n = layout_name(keys)
                return next((i for i, c in enumerate(r['choices']) if c['value'] == n), len(r['choices']) - 1)
            ch = r.get('choices', [])
            i = next((i for i, c in enumerate(ch) if c['value'].lower() == values[rid].lower()), -1)
            v = number(values[rid])
            if i < 0 and ch and v is not None and number(ch[0]['value']) is not None:   # decimals: the nearest step
                i = min(range(len(ch)), key=lambda j: abs(number(ch[j]['value']) - v))
            return i

        def label(self, rid):
            r = rows[rid]
            if r['type'] == 'text':
                return values[rid] or '(none)', r.get('note', '')
            i = self.choice_index(rid)
            if i < 0:
                return values[rid], r.get('note', '')
            c = r['choices'][i]
            return c['label'], c.get('note') or r.get('note', '')

        def cycle(self, rid, d):
            r = rows[rid]
            if r['type'] == 'text':
                return
            i = self.choice_index(rid)
            if r['type'] == 'controls':
                presets = [c['value'] for c in r['choices'] if c['value'] in layouts]   # Custom comes from editing keys
                i = i if 0 <= i < len(presets) else (-1 if d > 0 else 0)
                keys[:] = layouts[presets[(i + d) % len(presets)]]
            else:
                n = len(r['choices'])
                i = (i + d) % n if i >= 0 else (0 if d > 0 else n - 1)
                values[rid] = r['choices'][i]['value']
            self.update()

        # ---- geometry
        def row_h(self):
            """a panel's rows share the room between its title and the buttons: up to ROW_H tall, 4 apart"""
            if self.open < 0:
                return ROW_H
            n = len(self.items())
            return min(ROW_H, ((H - 84) - (BANNER + 54)) // n - 4) if n else ROW_H

        def row_rect(self, k):
            h = self.row_h()
            return QRect(ROW_X, (BANNER + 18 if self.open < 0 else BANNER + 54) + k * (h + (6 if self.open < 0 else 4)), ROW_W, h)

        def group_rect(self, g):
            top = BANNER + 18 + len(spec['top']) * (ROW_H + 6) + 14
            return QRect(ROW_X + (g % 2) * (ROW_W // 2 + 6), top + (g // 2) * 62, ROW_W // 2 - 6, 54)

        quit_rect = property(lambda self: QRect(ROW_X, H - 66, 150, 44))
        play_rect = property(lambda self: QRect(W - ROW_X - 200, H - 66, 200, 44))

        def guide_box(self):
            return QRect(ROW_X, BANNER + 50, ROW_W, H - BANNER - 140)

        def guide_hit(self, x, y):
            b = self.guide_box()
            per = (b.height() - 34) // 19
            x0, y0 = b.left() + 12, b.top() + 30
            if x < x0 or y < y0 or y >= y0 + per * 19:
                return None
            col, line = (x - x0) // (b.width() // 2), (y - y0) // 19
            i = col * per + line + self.scroll * per * 2
            return i if col <= 1 and i < len(spec['actions']) else None

        # ---- drawing
        def brackets(self, p, r, c):
            p.setPen(QPen(c, 1))
            l = 10
            x0, y0, x1, y1 = r.left(), r.top(), r.right(), r.bottom()
            for a, b in (((x0, y0 + l), (x0, y0)), ((x0, y0), (x0 + l, y0)), ((x1 - l, y0), (x1, y0)), ((x1, y0), (x1, y0 + l)),
                         ((x0, y1 - l), (x0, y1)), ((x0, y1), (x0 + l, y1)), ((x1 - l, y1), (x1, y1)), ((x1, y1), (x1, y1 - l))):
                p.drawLine(*a, *b)

        def text(self, p, r, s, font, color, flags=Qt.AlignVCenter | Qt.AlignLeft):
            p.setFont(font)
            p.setPen(color)
            p.drawText(r, flags, p.fontMetrics().elidedText(s, Qt.ElideRight, r.width()))

        def button(self, p, r, title, primary, hot):
            p.fillRect(r, QColor(40, 150, 150) if primary and hot else QColor(24, 110, 112) if primary else PANEL_HOT if hot else PANEL)
            p.setPen(QPen(ACCENT if primary else TEAL, 1))
            p.drawRect(r.adjusted(0, 0, -1, -1))
            self.text(p, r, title, self.f_big, QColor(255, 255, 255) if primary else TEAL, Qt.AlignCenter)

        def paintEvent(self, ev):
            p = QPainter(self)
            p.setRenderHint(QPainter.SmoothPixmapTransform)
            p.fillRect(self.rect(), BG)
            if art_img:
                p.drawImage(QRectF(0, 0, W, BANNER), art_img, QRectF(0, 16, 640, 170))
            else:
                self.text(p, QRect(0, 60, W, 50), 'RAINBOW SIX', self.f_title, QColor(255, 255, 255), Qt.AlignCenter)
            p.fillRect(QRect(0, BANNER - 24, W, 24), QColor(4, 8, 10))
            self.text(p, QRect(0, BANNER - 22, W - 16, 20), 'CO-OP EDITION  ·  ' + spec.get('version', ''), self.f_small, ACCENT,
                      Qt.AlignVCenter | Qt.AlignRight)
            p.setPen(TEAL_DIM)
            p.drawLine(0, BANNER, W, BANNER)
            if self.open >= 0:
                g = spec['groups'][self.open]
                self.text(p, QRect(ROW_X, BANNER + 14, ROW_W, 30), g['title'], self.f_big, TEAL)
                if g.get('guide'):
                    self.paint_guide(p)
                else:
                    for k in range(len(self.items())):
                        self.paint_row(p, k)
            else:
                for k in range(len(spec['top'])):
                    self.paint_row(p, k)
                for gi, g in enumerate(spec['groups']):
                    r = self.group_rect(gi)
                    hot = self.focus == len(spec['top']) + gi or self.hover == ('g', gi)
                    p.fillRect(r, PANEL_HOT if hot else PANEL)
                    self.brackets(p, r, TEAL if hot else TEAL_DIM)
                    self.text(p, QRect(r.left() + 14, r.top() + 4, r.width() - 28, 26), g['title'], self.f_big, TEAL)
                    summary = 'Every action\'s keys; rebind any of them' if g.get('guide') else \
                        ' · '.join(self.label(rid)[0] for rid in g['rows'])
                    self.text(p, QRect(r.left() + 14, r.top() + 30, r.width() - 28, 18), summary, self.f_small, NOTE)
            self.button(p, self.quit_rect, 'BACK' if self.open >= 0 else 'QUIT', False, self.hover == 'quit')
            self.button(p, self.play_rect, 'PLAY', True, self.hover == 'play')

        def paint_row(self, p, k):
            rid = self.items()[k]
            r = self.row_rect(k)
            hot = self.focus == k or self.hover == ('r', k)
            p.fillRect(r, PANEL_HOT if hot else PANEL)
            self.brackets(p, r, TEAL if hot else TEAL_DIM)
            h = r.height()
            self.text(p, QRect(r.left() + 16, r.top(), 200, h), rows[rid]['label'], self.f_row, NOTE)
            val, note = self.label(rid)
            top = r.top() + (h - 38) // 2
            if not (self.edit and self.edit.rid == rid):
                self.text(p, QRect(r.left() + 220, top + 2, r.width() - 270, 20), val, self.f_row, TEXT)
            self.text(p, QRect(r.left() + 220, top + 21, r.width() - 270, 16), note, self.f_small, NOTE)
            if rows[rid]['type'] != 'text':
                self.text(p, QRect(r.right() - 46, r.top(), 40, h), '<  >', self.f_row, TEAL, Qt.AlignCenter)

        def paint_guide(self, p):
            b = self.guide_box()
            p.fillRect(b, PANEL)
            self.brackets(p, b, TEAL_DIM)
            lay = {'classic': 'Classic', 'modern': 'Modern', 'keyboard': 'Keyboard Only'}.get(layout_name(keys), 'Custom')
            self.text(p, QRect(b.left() + 12, b.top() + 6, b.width() - 24, 18),
                      f'Layout: {lay}.  Click an action, then press a key or mouse button (Esc cancels, Delete clears).',
                      self.f_small, NOTE)
            per = (b.height() - 34) // 19
            for i, a in enumerate(spec['actions']):
                k = i - self.scroll * per * 2
                if not 0 <= k < per * 2:
                    continue
                col, line = divmod(k, per)
                x, y = b.left() + 12 + col * (b.width() // 2), b.top() + 30 + line * 19
                bound = ', '.join(key_names.get(c, f'#{c:02x}') for c in range(256) if keys[1 + c] == a['id'])
                if self.bind == i:
                    bound = 'press a key...'
                c = ACCENT if self.bind == i else TEXT if self.hover == ('a', i) else NOTE
                self.text(p, QRect(x, y, 210, 19), a['name'], self.f_small, c)
                self.text(p, QRect(x + 214, y, b.width() // 2 - 24 - 214, 19), bound or '-', self.f_small,
                          ACCENT if self.bind == i else TEXT)

        # ---- text rows
        def edit_begin(self, k):
            rid = self.items()[k]
            r = self.row_rect(k)
            e = QLineEdit(values[rid], self)
            e.rid = rid
            e.setMaxLength(rows[rid].get('textmax') or 31)
            e.setGeometry(r.left() + 218, r.top() + (r.height() - 24) // 2, r.width() - 280, 24)
            e.setStyleSheet('background:#0c2226;color:#d6ecec;border:1px solid #2ec4c4;font:11pt Arial')
            e.returnPressed.connect(lambda: self.edit_end(True))
            e.editingFinished.connect(lambda: self.edit_end(True))
            e.show()
            e.setFocus()
            e.selectAll()
            self.edit = e

        def edit_end(self, keep):
            if not self.edit:
                return
            e, self.edit = self.edit, None
            if keep:
                values[e.rid] = e.text()
            e.deleteLater()
            self.setFocus()
            self.update()

        # ---- input
        def mouseMoveEvent(self, ev):
            x, y = int(ev.position().x()), int(ev.position().y())
            hv = None
            if self.quit_rect.contains(x, y):
                hv = 'quit'
            elif self.play_rect.contains(x, y):
                hv = 'play'
            elif self.guide():
                a = self.guide_hit(x, y)
                hv = ('a', a) if a is not None else None
            else:
                for k in range(len(self.items())):
                    if self.row_rect(k).contains(x, y):
                        hv = ('r', k)
                if self.open < 0:
                    for g in range(len(spec['groups'])):
                        if self.group_rect(g).contains(x, y):
                            hv = ('g', g)
            if hv != self.hover:
                self.hover = hv
                self.update()

        def mousePressEvent(self, ev):
            x, y = int(ev.position().x()), int(ev.position().y())
            if self.bind is not None:
                code = {Qt.LeftButton: mouse.get('left'), Qt.RightButton: mouse.get('right'),
                        Qt.MiddleButton: mouse.get('middle')}.get(ev.button())
                if code:
                    self.do_bind(code)
                return
            if ev.button() != Qt.LeftButton:
                return
            self.edit_end(True)
            if self.quit_rect.contains(x, y):
                return self.back()
            if self.play_rect.contains(x, y):
                return self.play()
            if self.guide():
                a = self.guide_hit(x, y)
                if a is not None:
                    self.bind = a
                    self.update()
                return
            for k in range(len(self.items())):
                r = self.row_rect(k)
                if r.contains(x, y):
                    self.focus = k
                    rid = self.items()[k]
                    if rows[rid]['type'] != 'text' and r.right() - 46 <= x < r.right() - 26:
                        self.cycle(rid, -1)
                    else:
                        self.activate(k)
                    return
            if self.open < 0:
                for g in range(len(spec['groups'])):
                    if self.group_rect(g).contains(x, y):
                        return self.activate(len(spec['top']) + g)

        def wheelEvent(self, ev):
            if self.guide():
                self.scroll = max(0, min(2, self.scroll + (1 if ev.angleDelta().y() < 0 else -1)))
                self.update()

        def keyPressEvent(self, ev):
            k = ev.key()
            vk = ev.nativeVirtualKey()
            if self.bind is not None:
                if k == Qt.Key_Escape:
                    self.bind = None
                    self.update()
                elif k == Qt.Key_Delete:
                    self.do_bind(0)
                else:
                    code = vk_to_code.get(qt_to_vk(ev))
                    if code:
                        self.do_bind(code)
                return
            n = len(spec['top']) + len(spec['groups']) if self.open < 0 else len(self.items())
            if k == Qt.Key_Escape:
                self.back()
            elif k == Qt.Key_Up and not self.guide():
                self.focus = (self.focus - 1) % n
                self.update()
            elif k == Qt.Key_Down and not self.guide():
                self.focus = (self.focus + 1) % n
                self.update()
            elif k in (Qt.Key_Left, Qt.Key_Right) and not self.guide() and self.focus < len(self.items()):
                self.cycle(self.items()[self.focus], 1 if k == Qt.Key_Right else -1)
            elif k in (Qt.Key_Return, Qt.Key_Enter) and not self.guide():
                self.activate(self.focus)
            elif k in (Qt.Key_PageUp, Qt.Key_PageDown) and self.guide():
                self.scroll = max(0, min(2, self.scroll + (1 if k == Qt.Key_PageDown else -1)))
                self.update()

        def do_bind(self, code):
            aid = spec['actions'][self.bind]['id']
            if code:
                keys[1 + code] = aid
            else:
                for c in range(256):
                    if keys[1 + c] == aid:
                        keys[1 + c] = 0
            self.bind = None
            self.update()

        def activate(self, k):
            if k < len(self.items()) and not self.guide():
                rid = self.items()[k]
                if rows[rid]['type'] == 'text':
                    self.edit_begin(k)
                else:
                    self.cycle(rid, 1)
            elif self.open < 0 and len(spec['top']) <= k < len(spec['top']) + len(spec['groups']):
                self.open, self.focus, self.bind, self.scroll = k - len(spec['top']), 0, None, 0
            self.update()

        def back(self):
            self.edit_end(True)
            if self.open >= 0:
                self.open, self.focus, self.bind = -1, 0, None
                self.update()
            else:
                self.close()

        def play(self):
            self.edit_end(True)
            try:
                for rid, r in rows.items():
                    write_value(reg, r, values[rid])
                reg.save()
                write_kmp(kmp_path, keys)
            except OSError as e:
                QMessageBox.critical(self, 'Rainbow Six co-op', f"Couldn't save the settings: {e}")
                return
            self.close()
            # the frame-rate setting (the mod's R6CoopFrameRate) goes to the host's pacer; the mod leaves it to the host
            fps = next((values[rid] for rid, r in rows.items() if r.get('reg') == 'R6CoopFrameRate'), '0')
            if fps == '1000':
                os.environ['DSR_FPSCAP'], os.environ['DSR_VSYNC'] = '0', '0'          # unlimited
            elif fps.isdecimal() and int(fps) > 0:
                os.environ['DSR_FPSCAP'] = fps
            # Screen: the host's window (the native game itself always draws full screen)
            full = next((values[rid] for rid, r in rows.items() if r.get('reg') == 'FullScreen'), 'TRUE')
            os.environ['DS_WINDOW_MODE'] = 'windowed' if full.upper() == 'FALSE' else 'fullscreen'
            os.execv(command[0], command)

    def qt_to_vk(ev):
        """Qt key -> Windows virtual key (what the game's key codes are made from)"""
        k = ev.key()
        if Qt.Key_A <= k <= Qt.Key_Z or Qt.Key_0 <= k <= Qt.Key_9:
            return int(k)
        if Qt.Key_F1 <= k <= Qt.Key_F12:
            return 0x70 + (k - Qt.Key_F1)
        table = {Qt.Key_Backspace: 0x08, Qt.Key_Tab: 0x09, Qt.Key_Return: 0x0d, Qt.Key_Enter: 0x0d, Qt.Key_Shift: 0x10,
                 Qt.Key_Control: 0x11, Qt.Key_Alt: 0x12, Qt.Key_Pause: 0x13, Qt.Key_CapsLock: 0x14, Qt.Key_Space: 0x20,
                 Qt.Key_PageUp: 0x21, Qt.Key_PageDown: 0x22, Qt.Key_End: 0x23, Qt.Key_Home: 0x24, Qt.Key_Left: 0x25,
                 Qt.Key_Up: 0x26, Qt.Key_Right: 0x27, Qt.Key_Down: 0x28, Qt.Key_Insert: 0x2d, Qt.Key_Delete: 0x2e,
                 Qt.Key_NumLock: 0x90, Qt.Key_ScrollLock: 0x91, Qt.Key_Semicolon: 0xba, Qt.Key_Equal: 0xbb,
                 Qt.Key_Comma: 0xbc, Qt.Key_Minus: 0xbd, Qt.Key_Period: 0xbe, Qt.Key_Slash: 0xbf,
                 Qt.Key_QuoteLeft: 0xc0, Qt.Key_BracketLeft: 0xdb, Qt.Key_Backslash: 0xdc,
                 Qt.Key_BracketRight: 0xdd, Qt.Key_Apostrophe: 0xde}
        if ev.modifiers() & Qt.KeypadModifier and Qt.Key_0 <= k <= Qt.Key_9:
            return 0x60 + (k - Qt.Key_0)
        return table.get(k)

